// Embeds lib/src/figma/plugin_src/* into lib/src/figma/plugin_assets.g.dart
// so `dart run tokenline plugin` and `push` work from the published package.
//
//   dart run tool/embed_plugin.dart          # write
//   dart run tool/embed_plugin.dart --check  # exit 1 if stale (tests use this)
import 'dart:io';

const _src = 'lib/src/figma/plugin_src';
const _out = 'lib/src/figma/plugin_assets.g.dart';

String build() {
  String read(String name) {
    final text = File('$_src/$name').readAsStringSync();
    if (text.contains("'''")) {
      throw StateError("$name contains ''' and cannot be embedded");
    }
    return text;
  }

  final core = read('core.js');
  final code = '${read('core.js')}\n${read('main.js')}';
  String constant(String name, String doc, String value) =>
      "/// $doc\nconst $name = r'''\n$value''';\n";

  return [
    '// GENERATED by tool/embed_plugin.dart from $_src — DO NOT EDIT.\n'
        '// ignore_for_file: lines_longer_than_80_chars\n',
    constant('pluginCoreJs', 'Shared core: export, lint, fix, apply.', core),
    constant('pluginCodeJs', 'Plugin main file (core + UI wiring).', code),
    constant('pluginUiHtml', 'Plugin UI.', read('ui.html')),
    constant('pluginManifestJson', 'Plugin manifest.', read('manifest.json')),
  ].join('\n');
}

void main(List<String> args) {
  final content = build();
  final out = File(_out);
  if (args.contains('--check')) {
    if (!out.existsSync() || out.readAsStringSync() != content) {
      stderr.writeln('$_out is stale — run dart run tool/embed_plugin.dart');
      exit(1);
    }
    stdout.writeln('plugin assets current');
    return;
  }
  out.writeAsStringSync(content);
  stdout.writeln('wrote $_out');
}
