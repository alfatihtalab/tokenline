import 'dart:convert';
import 'dart:io';
import 'dart:math';

import '../errors.dart';
import '../figma/rest.dart';
import 'base.dart';

/// Figma components -> monochrome SVG string constants. One-way: Figma is
/// the only author of icons.
class IconsCommand extends TokenlineCommand {
  @override
  bool get hidden => true;

  IconsCommand() {
    argParser.addFlag('check',
        negatable: false,
        help: 'Fetch and compare only; exit 2 if the generated file is stale.');
  }

  @override
  String get name => 'icons';

  @override
  String get description =>
      'Pull icon components from Figma as SVG string constants.';

  @override
  Future<int> run() async {
    final icons = config.icons ??
        (throw TokenlineException('tokenline.yaml has no icons section'));
    final manifestFile = File(config.resolve(icons.manifest));
    if (!manifestFile.existsSync()) {
      throw TokenlineException('icon manifest not found: ${icons.manifest}');
    }
    final manifest =
        jsonDecode(manifestFile.readAsStringSync()) as Map<String, Object?>;
    final entries = ((manifest['icons'] as Map?) ?? const {})
        .cast<String, String>()
        .entries
        .toList()
      ..sort((a, b) => a.key.compareTo(b.key));
    if (entries.isEmpty) {
      throw TokenlineException('${icons.manifest} lists no icons '
          '(expected {"icons": {"constantName": "<figma node id>"}})');
    }

    final rest = FigmaRest(FigmaCredentials.resolve(config));
    final svgs = <String, String>{};
    try {
      info('resolving ${entries.length} icons…');
      final urls = <String, String>{};
      final ids = entries.map((e) => e.value).toSet().toList();
      for (var i = 0; i < ids.length; i += 50) {
        final batch = ids.sublist(i, min(i + 50, ids.length));
        final json = await rest.getJson('/v1/images/${rest.credentials.fileKey}'
            '?ids=${Uri.encodeQueryComponent(batch.join(','))}&format=svg');
        if (json['err'] != null) {
          throw TokenlineException('Figma images endpoint: ${json['err']}');
        }
        (json['images'] as Map).forEach((id, url) {
          if (url is String) urls[id as String] = url;
        });
      }
      final missing = entries.where((e) => !urls.containsKey(e.value)).toList();
      if (missing.isNotEmpty) {
        throw TokenlineException('${missing.length} icon(s) have no image in '
            'Figma (deleted or wrong node id): '
            '${missing.take(5).map((e) => '${e.key} (${e.value})').join(', ')}');
      }
      for (var i = 0; i < entries.length; i += 8) {
        final chunk = entries.sublist(i, min(i + 8, entries.length));
        await Future.wait(chunk.map((e) async {
          svgs[e.key] =
              normalizeSvg(await rest.download(Uri.parse(urls[e.value]!)));
        }));
      }
    } finally {
      rest.close();
    }

    final content = emitIcons(icons.className, icons.manifest, svgs);
    final out = File(config.resolve(icons.output));
    if (argResults!['check'] as bool) {
      final current = out.existsSync() ? out.readAsStringSync() : '';
      if (current != content) {
        throw TokenlineException(
            '${icons.output} is stale — run `dart run tokenline icons`',
            exitCode: 2);
      }
      info('icons are current (${svgs.length})');
      return 0;
    }
    out
      ..parent.createSync(recursive: true)
      ..writeAsStringSync(content);
    info('wrote ${icons.output} (${svgs.length} icons)');
    return 0;
  }
}

/// One line, every color pinned to black so call sites can tint freely.
String normalizeSvg(String svg) => svg
    .replaceAll(RegExp(r'#[0-9a-fA-F]{6}'), '#000000')
    .replaceAll(RegExp(r'#[0-9a-fA-F]{3}\b'), '#000')
    .replaceAll(RegExp(r'\s*\n\s*'), ' ')
    .trim();

String emitIcons(String className, String manifest, Map<String, String> svgs) {
  final b = StringBuffer()
    ..writeln(
        '// GENERATED by `dart run tokenline icons` from $manifest — DO NOT EDIT.')
    ..writeln('//')
    ..writeln(
        '// Monochrome SVG strings from Figma; ink normalized to #000000.')
    ..writeln('// Tint at the call site:')
    ..writeln('//   SvgPicture.string($className.name,')
    ..writeln('//     colorFilter: ColorFilter.mode(color, BlendMode.srcIn))')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln('abstract final class $className {');
  for (final key in svgs.keys.toList()..sort()) {
    final escaped = svgs[key]!
        .replaceAll(r'\', r'\\')
        .replaceAll("'", r"\'")
        .replaceAll(r'$', r'\$');
    b.writeln("  static const String $key = '$escaped';");
  }
  b.writeln('}');
  return b.toString();
}
