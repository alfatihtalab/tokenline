const pushFormat = 'tokenline.figma-push';

/// The rules the plugin needs, stored in the Figma file by every push.
Map<String, Object?> pluginConfig(TokenlineConfig config) {
  final figma = config.figma!;
  return {
    'collections': {
      for (final e in figma.collections.entries) e.key.name: e.value,
    },
    'modes': figma.modes,
    'primitiveMode': figma.primitiveMode,
    'componentMode': figma.componentMode,
    'nameCase': figma.nameCase.name,
    'hidePrimitives': figma.hidePrimitives,
    'groups': config.lint.groups.toList(),
  };
}

/// What `tokenline push` sends to Figma: collections, modes and variables
/// as the token files describe them.
Map<String, Object?> buildPushPayload(TokenlineConfig config, FigmaPlan plan) {
  final figma = config.figma!;
  return {
    'format': pushFormat,
    'version': 1,
    'tokenline': {'name': config.name, 'version': config.version},
    'config': pluginConfig(config),
    'collections': [
      for (final MapEntry(key: level, value: name) in figma.collections.entries)
        {
          'level': level.name,
          'name': name,
          'modes': switch (level) {
            Level.primitives => [figma.primitiveMode],
            Level.semantic => figma.modes.values.toList(),
            Level.components => [figma.componentMode],
          },
        },
    ],
    'variables': [
      for (final v in plan.variables)
        {
          'path': v.path,
          'level': v.level.name,
          'name': v.name,
          'collection': v.collection,
          'type': v.figmaType,
          'description': v.figmaDescription,
          'scopes': v.scopes,
          'hiddenFromPublishing': v.hiddenFromPublishing,
          if (v.codeSyntax != null) 'codeSyntax': v.codeSyntax,
          'values': {
            for (final MapEntry(key: mode, value: value) in v.values.entries)
              mode: switch (value) {
                PlannedRaw(:final value) => value,
                PlannedAlias(:final targetName, :final targetCollection) => {
                    'alias': targetName,
                    'collection': targetCollection,
                  },
              },
          },
        },
    ],
    if (figma.source == FigmaSource.syncFrame)
      'syncFrame': {
        'id': figma.syncFrameId,
        'semanticCollection': figma.collections[Level.semantic],
        'modes': figma.modes,
      },
  };
}

/// Claude's use_figma tool accepts scripts up to 50,000 characters.
const maxScriptChars = 48000;

/// Scripts that apply [payload] when run inside Figma (Claude's use_figma
/// tool, or any runner that wraps code in an async function).
///
/// A payload too big for one script is split into parts, primitives first,
/// so every link points at a variable an earlier part (or the same part)
/// created. Run the parts in order. Only the last part stores the plugin
/// rules, rebuilds a legacy sync frame and — with [prune] — deletes extras,
/// using the full list of variables to keep.
List<String> buildPushScripts(Map<String, Object?> payload,
    {required bool prune, int maxChars = maxScriptChars}) {
  final variables = (payload['variables'] as List).cast<Map<String, Object?>>();
  final base = {
    for (final e in payload.entries)
      if (!const {'variables', 'config', 'syncFrame'}.contains(e.key))
        e.key: e.value,
  };
  final last = {
    if (payload['config'] != null) 'config': payload['config'],
    if (payload['syncFrame'] != null) 'syncFrame': payload['syncFrame'],
  };

  String script(Map<String, Object?> part, int index, int count) => '''
// GENERATED by `dart run tokenline push` — do not edit.
// ${count == 1 ? 'Applies' : 'Part $index of $count: applies'} the token files to this Figma file: creates and
// updates variables${prune && index == count ? ' and DELETES variables that are not in the tokens' : '; never deletes'}.
// Run it with Claude (use_figma)${count == 1 ? '' : ', parts in order'}, or use the Tokenline
// plugin's Import with the matching .json file.
const TOKENLINE_PAYLOAD = ${jsonEncode(part)};

$pluginApplyJs
return await figmaApplyPayload(TOKENLINE_PAYLOAD, { prune: ${prune && index == count} });
''';

  final whole = script({...base, ...last, 'variables': variables}, 1, 1);
  if (whole.length <= maxChars) return [whole];

  // Greedy split by encoded size; the keep-list rides with the last part.
  final keep = [for (final v in variables) '${v['collection']}|${v['name']}'];
  final overhead =
      script({...base, ...last, if (prune) 'keep': keep, 'variables': []}, 9, 9)
          .length;
  final budget = maxChars - overhead;
  if (budget < 2000) {
    throw StateError('push payload overhead leaves no room for variables');
  }
  final parts = <List<Map<String, Object?>>>[[]];
  var size = 0;
  for (final v in variables) {
    final s = jsonEncode(v).length + 1;
    if (size + s > budget && parts.last.isNotEmpty) {
      parts.add([]);
      size = 0;
    }
    parts.last.add(v);
    size += s;
  }
  return [
    for (var i = 0; i < parts.length; i++)
      script({
        ...base,
        if (i == parts.length - 1) ...last,
        if (i == parts.length - 1 && prune) 'keep': keep,
        'variables': parts[i],
      }, i + 1, parts.length),
  ];
}
